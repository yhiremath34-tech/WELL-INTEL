// Helper to generate 7d, 30d, 6m, 1y historical telemetry series for any well
export function getMockHistoricalTelemetry(well: Well, period: '7d' | '30d' | '6m' | '1y'): {
  date: string;
  waterLevel: number; // in meters below ground level (lower is more water)
  rechargeRate: number; // L/hr
  qualityScore: number; // 0 to 100
}[] {
  const points = period === '7d' ? 7 : period === '30d' ? 15 : period === '6m' ? 24 : 36;
  const data = [];
  const baseLevel = well.water_level;
  const baseYield = well.yield;
  const now = new Date();

  for (let i = points - 1; i >= 0; i--) {
    const d = new Date(now);
    if (period === '7d') {
      d.setDate(d.getDate() - i);
    } else if (period === '30d') {
      d.setDate(d.getDate() - i * 2);
    } else if (period === '6m') {
      d.setDate(d.getDate() - i * 7);
    } else {
      d.setDate(d.getDate() - i * 10);
    }

    // Small smooth seasonal / diurnal variance
    const variance = Math.sin(i * 0.45) * 1.8 + (Math.cos(i * 0.2) * 0.7);
    const calculatedLevel = Math.max(1, Math.round((baseLevel + variance) * 10) / 10);
    const calculatedYield = Math.max(200, Math.round(baseYield - variance * 45));
    const qualityScore = well.water_quality === 'Good' ? 92 - Math.abs(variance) * 2 :
                         well.water_quality === 'Moderate' ? 74 - Math.abs(variance) * 3 : 52;

    data.push({
      date: period === '7d' 
        ? d.toLocaleDateString('en-US', { weekday: 'short' })
        : d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
      waterLevel: calculatedLevel,
      rechargeRate: calculatedYield,
      qualityScore: Math.round(qualityScore),
    });
  }
  return data;
}
